def main():
    print(f"Total cosmetic products to add: {len(COSMETIC_PRODUCTS)}")
    catalog_path = ROOT / 'data/catalog.json'
    catalog = json.loads(catalog_path.read_text())

    analysis_path = ROOT / 'data/review-analysis.json'
    analysis = json.loads(analysis_path.read_text())

    annotations_path = ROOT / 'data/review-annotations.json'
    annotations = json.loads(annotations_path.read_text())

    existing_ids = {p['id'] for p in catalog['products']}
    print(f"Existing products: {len(existing_ids)}")

    for p in COSMETIC_PRODUCTS:
        pid = p['id']
        if pid in existing_ids:
            print(f"Skipping already existing {pid}")
            continue

        pos_id, pos_label, pos_desc = p['positiveTopic']
        neg_id, neg_label, neg_desc = p['negativeTopic']

        # 1. Annotations
        ann_reviews = []
        for i, rev in enumerate(p['reviews']):
            rid = rev[6]
            pos_tags = [pos_id] if rev[3] == 'positive' or i < 4 else []
            neg_tags = [neg_id] if rev[3] in ('mixed', 'neutral') or i == 1 else []
            ann_reviews.append({
                "sourceReviewId": rid,
                "positive": pos_tags,
                "negative": neg_tags
            })

        ann_excerpts = []
        for exc in p['excerpts']:
            ann_excerpts.append({
                "sourceReviewId": exc[0],
                "text": exc[1],
                "topicId": exc[4]
            })

        annotations['products'][pid] = {
            "reviews": ann_reviews,
            "excerpts": ann_excerpts,
            "topics": {
                "positive": [{"id": pos_id, "label": pos_label, "description": pos_desc}],
                "negative": [{"id": neg_id, "label": neg_label, "description": neg_desc}]
            }
        }

        # 2. Review Analysis
        evidence = []
        for rev in p['reviews']:
            evidence.append({
                "sourceReviewId": rev[6],
                "author": rev[0],
                "sourceRating": rev[1],
                "date": None,
                "sourceUrl": p['sourceUrl'],
                "textSha256": hashlib.sha256(rev[5].encode('utf-8')).hexdigest()
            })

        pos_rids = [r['sourceReviewId'] for r in ann_reviews if pos_id in r['positive']]
        neg_rids = [r['sourceReviewId'] for r in ann_reviews if neg_id in r['negative']]

        orig_excerpts = []
        for exc in p['excerpts']:
            orig_excerpts.append({
                "sourceReviewId": exc[0],
                "author": exc[2],
                "sourceRating": exc[3],
                "text": exc[1],
                "adStatus": "확인 불가",
                "topicId": exc[4],
                "isExcerpt": True,
                "sourceUrl": p['sourceUrl']
            })

        analysis['products'][pid] = {
            "reviewSampleCount": len(p['reviews']),
            "reviewEvidence": evidence,
            "mentionGroups": {
                "positive": [{"id": pos_id, "label": pos_label, "description": pos_desc, "count": len(pos_rids), "reviewIds": pos_rids}],
                "negative": [{"id": neg_id, "label": neg_label, "description": neg_desc, "count": len(neg_rids), "reviewIds": neg_rids}]
            },
            "originalExcerpts": orig_excerpts,
            "unclassifiedReviewCount": sum(not r['positive'] and not r['negative'] for r in ann_reviews)
        }

        # 3. Product catalog entry
        prod_reviews = []
        for i, rev in enumerate(p['reviews']):
            prod_reviews.append({
                "id": f"{pid}-{i+1}",
                "topic": rev[2],
                "tone": rev[3],
                "title": rev[4],
                "summary": rev[5],
                "sourceReviewId": rev[6],
                "author": rev[0],
                "sourceRating": rev[1],
                "sourceUrl": p['sourceUrl'],
                "summaryType": "원문을 읽고 재구성한 요약",
                "date": None,
                "adStatus": "확인 불가"
            })

        img_path = ROOT / f"assets/catalog/{pid}.webp"
        img_sha = hashlib.sha256(img_path.read_bytes()).hexdigest() if img_path.exists() else "placeholder"

        catalog['products'].append({
            "id": pid,
            "brand": p['brand'],
            "name": p['name'],
            "subtitle": p['subtitle'],
            "category": p['category'],
            "categoryName": p['categoryName'],
            "source": "11번가",
            "sourceUrl": p['sourceUrl'],
            "sourceTitle": p['sourceTitle'],
            "sourceRating": p['sourceRating'],
            "sourceReviewCount": p['sourceReviewCount'],
            "observedPrice": p['observedPrice'],
            "image": f"assets/catalog/{pid}.webp",
            "imageSourceUrl": p['imageUrl'],
            "imageSha256": img_sha,
            "reviewSampleCount": len(p['reviews']),
            "collectedAt": "2026-11-08T23:10:00+09:00",
            "sourceReviewDatesAvailable": False,
            "lead": p['lead'],
            "good": p['good'],
            "caution": p['caution'],
            "tags": p['tags'],
            "reviews": prod_reviews,
            "reviewAnalysis": analysis['products'][pid]
        })

    # Update summary counts
    catalog['reviewSampleCount'] = sum(prod['reviewSampleCount'] for prod in catalog['products'])
    catalog['summaryCount'] = sum(len(prod['reviews']) for prod in catalog['products'])
    catalog['originalExcerptCount'] = sum(len(prod['reviewAnalysis']['originalExcerpts']) for prod in catalog['products'])

    # Write files
    annotations_path.write_text(json.dumps(annotations, ensure_ascii=False, indent=2) + '\n')
    analysis_path.write_text(json.dumps(analysis, ensure_ascii=False, indent=2) + '\n')
    catalog_path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + '\n')
    (ROOT / 'data/catalog.viewer.json').write_text(json.dumps(catalog))

    print(f"Success! Total products now: {len(catalog['products'])}, Total review samples: {catalog['reviewSampleCount']}")

if __name__ == '__main__':
    main()
